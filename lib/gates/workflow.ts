/**
 * Generates the GitHub Actions workflow that turns Splitfire acceptance checks into real check
 * runs. The workflow is repo-agnostic: it discovers the plan and the task at run time, so the same
 * file works for every plan and can be committed alongside `.splitfire/plan.json`.
 *
 * Trust model: a push can only choose the task label (Tn), and that label must match
 * `^T[0-9]+$`. Commands come from the plan file, are re-classified by the embedded parser, and
 * anything that is not a known command or file check is reported as manual and never executed.
 */

export const GATES_WORKFLOW_PATH = ".github/workflows/splitfire-gates.yml";

/** The check run name prefix; the full name is `splitfire/Tn`, exactly as the contract says. */
export const GATES_CHECK_PREFIX = "splitfire/";

export function generateGatesWorkflow(plan: { tasks: readonly { id: string }[] }): string {
  if (!Array.isArray(plan.tasks)) throw new Error("generateGatesWorkflow needs a plan with tasks");

  const lines = [
    "# Generated by Splitfire. Do not edit by hand; regenerate it from .splitfire/plan.json.",
    "#",
    "# When an agent pushes a splitfire/Tn branch, this workflow runs task Tn's acceptance",
    "# checks from .splitfire/plan.json and reports a check run named splitfire/Tn on that",
    "# commit. Only commands recognised in the plan file are executed; prose stays manual.",
    "name: Splitfire gates",
    "",
    "on:",
    "  push:",
    "    branches:",
    '      - "splitfire/**"',
    "",
    "# Minimal permissions: read the repo, write check runs. Nothing else.",
    "permissions:",
    "  contents: read",
    "  checks: write",
    "",
    "concurrency:",
    "  group: splitfire-gates-${{ github.ref }}",
    "  cancel-in-progress: true",
    "",
    "jobs:",
    "  gate:",
    "    name: splitfire gate",
    "    runs-on: ubuntu-latest",
    "    timeout-minutes: 30",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "        with:",
    "          fetch-depth: 0",
    "",
    "      - name: Install dependencies",
    "        run: |",
    "          if [ -f package-lock.json ]; then",
    "            npm ci",
    "          elif [ -f pnpm-lock.yaml ]; then",
    "            corepack enable && pnpm install --frozen-lockfile",
    "          elif [ -f yarn.lock ]; then",
    "            corepack enable && yarn install --immutable",
    "          elif [ -f bun.lockb ]; then",
    "            npm install -g bun && bun install --frozen-lockfile",
    "          else",
    "            echo 'No JavaScript lockfile; skipping dependency install.'",
    "          fi",
    "",
    "      - name: Run acceptance checks",
    "        run: |",
    '          mkdir -p "$RUNNER_TEMP/splitfire"',
    "          cat > \"$RUNNER_TEMP/splitfire/gate.mjs\" <<'SPLITFIRE_GATE_EOF'",
    ...block(GATE_RUNNER_SCRIPT, 10).split("\n"),
    "          SPLITFIRE_GATE_EOF",
    '          node "$RUNNER_TEMP/splitfire/gate.mjs"',
    "",
    "      - name: Report check run",
    "        if: always()",
    "        env:",
    "          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}",
    "        run: |",
    '          mkdir -p "$RUNNER_TEMP/splitfire"',
    "          cat > \"$RUNNER_TEMP/splitfire/report.mjs\" <<'SPLITFIRE_REPORT_EOF'",
    ...block(REPORT_SCRIPT, 10).split("\n"),
    "          SPLITFIRE_REPORT_EOF",
    '          node "$RUNNER_TEMP/splitfire/report.mjs"',
    "",
  ];
  return lines.join("\n");
}

/** Indents a script for a YAML block scalar, leaving blank lines truly blank. */
function block(text: string, indent: number): string {
  const pad = " ".repeat(indent);
  return text
    .split("\n")
    .map((line) => (line.length > 0 ? pad + line : line))
    .join("\n");
}

/**
 * Runs inside the workflow. Reads the plan, maps the validated branch label to a plan task, runs
 * that task's runnable checks and writes `result.json` for the reporter. Exported so tests can
 * execute it directly against a fixture repo.
 */
export const GATE_RUNNER_SCRIPT = String.raw`
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const BRANCH = process.env.GITHUB_REF_NAME || "";
const COMMIT = process.env.GITHUB_SHA || "";
const OUT_DIR = join(process.env.RUNNER_TEMP || ".", "splitfire");
const RESULT_PATH = join(OUT_DIR, "result.json");
const MAX_COMMAND_LENGTH = 300;
const MAX_PATH_LENGTH = 240;
const HEADS = [
  "npm", "pnpm", "yarn", "npx", "vitest", "playwright",
  "pytest", "tsc", "go", "cargo", "python", "python3", "bun"
];
const BAD = [";", "&", "|", "<", ">", "\x60", "$"];
const CONTROL = /[\u0000-\u001f\u007f]/;
const QUOTES = /["'\x60]/;
const SAFE_PATH = /^[A-Za-z0-9._@+\/-]+$/;
const PATH_TOKEN =
  "(?:[A-Za-z0-9._@+-]+/)*[A-Za-z0-9._@+-]*\\.[A-Za-z0-9]+|[A-Za-z0-9._@+-]+(?:/[A-Za-z0-9._@+-]+)+";
const PROSE_FILE = new RegExp("^(?:file\\s+)?(" + PATH_TOKEN + ")\\s+(?:must\\s+)?exists?\\.?$", "i");
const BACKTICKED_FILE = new RegExp(
  "^(?:file\\s+)?\x60([^\x60]+)\x60\\s+(?:must\\s+)?exists?\\.?$",
  "i"
);

function writeResult(result) {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(RESULT_PATH, JSON.stringify(result, null, 2) + "\n");
}

function finish(result) {
  writeResult(result);
  if (result.skip) {
    console.log("Splitfire gates skipped: " + result.reason);
    process.exit(0);
  }
  console.log("Splitfire gates " + result.label + ": " + result.conclusion);
  process.exit(result.conclusion === "success" ? 0 : 1);
}

function stripMarkers(line) {
  let value = line;
  for (;;) {
    const next = value
      .replace(/^\[[ xX]\]\s+/, "")
      .replace(/^(?:[-*]|\d+[.)])\s+/, "")
      .replace(/^\$\s+/, "")
      .trim();
    if (next === value) return value;
    value = next;
  }
}

function safePath(raw) {
  const path = raw.trim().replace(/^\.\//, "");
  if (!path || path.length > MAX_PATH_LENGTH) return null;
  if (!SAFE_PATH.test(path)) return null;
  if (path.charAt(0) === "/" || path.charAt(0) === "-" || path.charAt(0) === "~") return null;
  for (const segment of path.split("/")) {
    if (segment === "" || segment === "." || segment === "..") return null;
  }
  return path;
}

function matchFile(line) {
  const test = /^test\s+-(f|e)\s+(?:'([^']+)'|"([^"]+)"|(\S+))$/.exec(line);
  const bracket = test
    ? null
    : /^\[\s+-(f|e)\s+(?:'([^']+)'|"([^"]+)"|(\S+))\s+\]$/.exec(line);
  const prose = test || bracket ? null : PROSE_FILE.exec(line);
  const quoted = test || bracket || prose ? null : BACKTICKED_FILE.exec(line);

  let raw;
  let flag = "f";
  const explicit = test || bracket;
  if (explicit) {
    flag = explicit[1] === "e" ? "e" : "f";
    raw = explicit[2] || explicit[3] || explicit[4];
  } else if (prose) {
    raw = prose[1];
  } else if (quoted) {
    raw = quoted[1];
  } else {
    return null;
  }

  const path = safePath(raw || "");
  return path ? { path: path, flag: flag } : "invalid";
}

function classifyCommand(raw) {
  const command = raw.trim().replace(/\s+/g, " ");
  if (!command) return { reason: "not-a-command" };
  if (command.length > MAX_COMMAND_LENGTH) return { reason: "unsafe" };
  for (const character of BAD) {
    if (command.indexOf(character) !== -1) return { reason: "unsafe" };
  }
  if (CONTROL.test(command) || QUOTES.test(command)) return { reason: "unsafe" };

  const tokens = command.split(" ");
  const head = tokens[0];
  if (HEADS.indexOf(head) === -1) return { reason: "not-a-command" };
  if ((head === "python" || head === "python3") && (tokens[1] !== "-m" || tokens[2] !== "py_compile")) {
    return { reason: "not-a-command" };
  }
  return { command: command };
}

function parseAcceptance(acceptance) {
  const runnable = [];
  const manual = [];
  const seen = new Set();
  const add = (check) => {
    if (seen.has(check.command)) return;
    seen.add(check.command);
    runnable.push(check);
  };

  for (const raw of acceptance) {
    const source = typeof raw === "string" ? raw.trim() : "";
    if (!source) continue;
    const line = stripMarkers(source);
    if (!line) continue;

    const file = matchFile(line);
    if (file === "invalid") {
      manual.push({ source: source, reason: "unsafe" });
      continue;
    }
    if (file) {
      add({ source: source, kind: "file", command: "test -" + file.flag + " '" + file.path + "'" });
      continue;
    }

    const spans = [];
    const pattern = /\x60([^\x60]+)\x60/g;
    let match = pattern.exec(line);
    while (match) {
      const span = (match[1] || "").trim();
      if (span) spans.push(span);
      match = pattern.exec(line);
    }

    if (spans.length > 0) {
      const parsed = spans.map(classifyCommand);
      const commands = parsed.filter((p) => p.command);
      if (commands.length === parsed.length) {
        for (const p of commands) add({ source: source, kind: "command", command: p.command });
      } else {
        const unsafe = parsed.some((p) => !p.command && p.reason === "unsafe");
        manual.push({ source: source, reason: unsafe ? "unsafe" : "not-a-command" });
      }
      continue;
    }

    const direct = classifyCommand(line);
    if (direct.command) add({ source: source, kind: "command", command: direct.command });
    else manual.push({ source: source, reason: direct.reason });
  }

  return { runnable: runnable, manual: manual };
}

/** Mirrors lib/partition/waves.ts: labels are assigned wave by wave, in plan order. */
function labelMap(tasks) {
  const ids = new Set(tasks.map((t) => t.id));
  const byId = new Map(tasks.map((t) => [t.id, t]));
  const depth = new Map();
  const visit = (id, seen) => {
    if (depth.has(id)) return depth.get(id);
    if (seen.has(id)) return 0;
    seen.add(id);
    const task = byId.get(id);
    const deps = (task && Array.isArray(task.dependsOn) ? task.dependsOn : []).filter(
      (dep) => ids.has(dep) && dep !== id
    );
    const value = deps.length === 0 ? 0 : 1 + Math.max.apply(null, deps.map((dep) => visit(dep, seen)));
    depth.set(id, value);
    return value;
  };
  tasks.forEach((task) => visit(task.id, new Set()));

  const waves = [];
  for (const task of tasks) {
    const index = depth.get(task.id) || 0;
    while (waves.length <= index) waves.push([]);
    waves[index].push(task.id);
  }

  const labels = new Map();
  for (const wave of waves) for (const id of wave) labels.set(id, "T" + labels.size);
  return labels;
}

function tail(text, max) {
  if (text.length <= max) return text;
  return "..." + text.slice(text.length - max);
}

const branchMatch = /^splitfire\/(T[0-9]+)$/.exec(BRANCH);
if (!branchMatch) {
  finish({ skip: true, reason: "branch " + BRANCH + " is not splitfire/T<n>" });
}
const label = branchMatch[1];

let plan;
try {
  plan = JSON.parse(readFileSync(".splitfire/plan.json", "utf8"));
} catch (error) {
  finish({
    skip: false,
    label: label,
    conclusion: "failure",
    checks: [],
    manual: [],
    summary:
      "Could not read .splitfire/plan.json on this branch: " +
      (error && error.message ? error.message : String(error)),
  });
}

const tasks = plan && Array.isArray(plan.tasks) ? plan.tasks : [];
const labels = labelMap(tasks);
const task = tasks.find((candidate) => labels.get(candidate.id) === label);
if (!task) {
  finish({
    skip: false,
    label: label,
    conclusion: "failure",
    checks: [],
    manual: [],
    summary:
      "No task " + label + " in .splitfire/plan.json. The plan has " + tasks.length + " task(s).",
  });
}

const acceptance = Array.isArray(task.acceptance) ? task.acceptance : [];
const parsed = parseAcceptance(acceptance);
const checks = [];
// Dry run is for tests only: it records what would run and executes nothing.
const dryRun = process.env.SPLITFIRE_GATE_DRY_RUN === "1";

for (const item of parsed.runnable) {
  const started = Date.now();
  if (dryRun) {
    checks.push({
      source: item.source,
      kind: item.kind,
      command: item.command,
      status: "dry-run",
      exitCode: 0,
      seconds: 0,
      output: "",
    });
    continue;
  }
  console.log("::group::" + item.command);
  const run = spawnSync("/bin/bash", ["-eo", "pipefail", "-c", item.command], {
    encoding: "utf8",
    timeout: 20 * 60 * 1000,
    maxBuffer: 32 * 1024 * 1024,
  });
  const output = [(run.stdout || ""), (run.stderr || "")].join("").trim();
  if (output) console.log(output);
  console.log("::endgroup::");

  const failed = Boolean(run.error) || run.status !== 0;
  if (failed) console.log("::error::" + item.command + " failed");
  checks.push({
    source: item.source,
    kind: item.kind,
    command: item.command,
    status: failed ? "failed" : "passed",
    exitCode: run.status === null ? -1 : run.status,
    seconds: Math.round((Date.now() - started) / 1000),
    output: tail(output, 2000),
  });
}

const passed = checks.filter((check) => check.status === "passed").length;
const failed = checks.length - passed;
const conclusion = checks.length === 0 || failed > 0 ? "failure" : "success";

const summary = [];
summary.push("**" + label + " - " + task.title + "**");
summary.push("");
if (checks.length === 0) {
  summary.push("No runnable acceptance checks, so nothing could be verified.");
} else {
  summary.push(passed + " passed, " + failed + " failed, " + parsed.manual.length + " manual.");
}
for (const check of checks) {
  summary.push(
    "- " +
      (check.status === "passed" ? "PASS" : "FAIL (exit " + check.exitCode + ")") +
      ": " +
      check.command
  );
}
for (const item of parsed.manual) {
  summary.push("- MANUAL (" + item.reason + "): " + item.source);
}
for (const check of checks) {
  if (check.status === "passed") continue;
  summary.push("", "Output of " + check.command + ":", check.output || "(no output)");
}

finish({
  skip: false,
  label: label,
  title: task.title,
  branch: BRANCH,
  commit: COMMIT,
  conclusion: conclusion,
  checks: checks,
  manual: parsed.manual,
  summary: tail(summary.join("\n"), 60000),
});
`.trim();

/**
 * Runs inside the workflow after the checks. Posts the check run named `splitfire/Tn` with the
 * minimal token, and skips silently on branches that are not `splitfire/Tn`.
 */
export const REPORT_SCRIPT = String.raw`
import { appendFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

const BRANCH = process.env.GITHUB_REF_NAME || "";
const SHA = process.env.GITHUB_SHA || "";
const match = /^splitfire\/(T[0-9]+)$/.exec(BRANCH);
if (!match) {
  console.log("Splitfire gates: branch " + BRANCH + " is not splitfire/T<n>; no check run created.");
  process.exit(0);
}

const label = match[1];
const name = "splitfire/" + label;
let result = null;
try {
  result = JSON.parse(
    readFileSync(join(process.env.RUNNER_TEMP || ".", "splitfire", "result.json"), "utf8")
  );
} catch (error) {
  result = null;
}

const conclusion = result && result.conclusion === "success" ? "success" : "failure";
const summary =
  result && result.summary
    ? result.summary
    : "The Splitfire gate did not report a result (a setup step failed before the checks ran). See the workflow logs.";
const title = result && result.title ? name + ": " + result.title : name;

const api = process.env.GITHUB_API_URL || "https://api.github.com";
const repo = process.env.GITHUB_REPOSITORY || "";
const server = process.env.GITHUB_SERVER_URL || "https://github.com";
const runId = process.env.GITHUB_RUN_ID || "";

const payload = {
  name: name,
  head_sha: SHA,
  status: "completed",
  conclusion: conclusion,
  output: { title: tail(title, 255), summary: tail(summary, 65000) },
};
if (runId) payload.details_url = server + "/" + repo + "/actions/runs/" + runId;

const response = await fetch(api + "/repos/" + repo + "/check-runs", {
  method: "POST",
  headers: {
    Authorization: "Bearer " + (process.env.GITHUB_TOKEN || ""),
    Accept: "application/vnd.github+json",
    "X-GitHub-Api-Version": "2022-11-28",
    "Content-Type": "application/json",
  },
  body: JSON.stringify(payload),
});

const body = await response.text();
if (!response.ok) {
  console.error("Could not create check run " + name + ": " + response.status + " " + body);
  process.exit(1);
}

const created = JSON.parse(body);
console.log("Created check run " + name + " (" + conclusion + "): " + (created.html_url || created.url || ""));
if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, summary + "\n");

function tail(text, max) {
  if (text.length <= max) return text;
  return text.slice(0, max - 3) + "...";
}
`.trim();
